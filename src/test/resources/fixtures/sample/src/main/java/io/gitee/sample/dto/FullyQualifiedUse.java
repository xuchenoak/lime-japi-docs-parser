package io.gitee.sample.dto;

/**
 * Uses fully-qualified type names without import statements
 */
public class FullyQualifiedUse {

    /**
     * fully qualified java.util.Date without import
     */
    private java.util.Date createTime;

    /**
     * fully qualified JDK inner type without import
     */
    private java.util.Map.Entry<String, String> entry;
}